// Cloudflare Worker entry (wrangler.jsonc "main"). Wraps the OpenNext handler
// generated at build time (.open-next/worker.js) — the custom-worker pattern
// from https://opennext.js.org/cloudflare/howtos/custom-worker.
//
// Two jobs, both cheap enough for the Workers Free plan's 10 ms CPU limit:
//  1. Old /question/<slug>-<id> URLs (en and /hi): answer the 301 from the
//     build-time map (lib/seo/question-redirect-map.ts) without loading Next.js.
//     Through Next, each one cost 17–440 ms of CPU. A question missing from
//     the map falls through to the route handler, which computes it as before.
//  2. Staging (env STAGING=1): mark every response noindex so the workers.dev
//     copy never competes with academy.clearcutoff.in in search results.

// @ts-ignore: generated by `opennextjs-cloudflare build`
import { default as handler } from "./.open-next/worker.js";

type Env = { ASSETS: { fetch(request: Request | string): Promise<Response> }; STAGING?: string };
type Ctx = { waitUntil(promise: Promise<unknown>): void; passThroughOnException(): void };

/** Keep in sync with QUESTION_REDIRECT_SHARDS (lib/seo/question-redirect-map.ts). */
const SHARDS = 64;
/** Where the deploy workflows copy the prerendered shards. */
const SHARD_DIR = "/_question-redirects";

// Same id rule as parseQuestionId (lib/seo/question-redirect.ts): the id is
// the trailing number of the last path segment.
const QUESTION_PATH = /^\/(?:(hi)\/)?question\/(?:.*\/)?(?:[^/]*-)?(\d+)\/?$/;

async function questionRedirect(request: Request, env: Env): Promise<Response | null> {
  const url = new URL(request.url);
  const match = QUESTION_PATH.exec(url.pathname);
  if (!match) return null;
  const [, hi, id] = match;

  const shard = await env.ASSETS.fetch(`${url.origin}${SHARD_DIR}/${Number(id) % SHARDS}.json`);
  if (!shard.ok) return null;
  const entry = ((await shard.json()) as Record<string, [string, number, 0 | 1]>)[id];
  if (!entry) return null;

  // Built exactly like chapterPageUrl(): /hi only when that page is a
  // genuinely Hindi page, the original query kept, the question as the hash.
  const [path, page, hindi] = entry;
  const locale = hi && hindi ? "/hi" : "";
  const pageSuffix = page > 1 ? `/page/${page}` : "";
  const search = url.search && url.search !== "?" ? url.search : "";
  return new Response(null, {
    status: 301,
    headers: {
      Location: `${url.origin}${locale}${path}${pageSuffix}${search}#q-${id}`,
      // An hour, as the route handler: the page can change on the next build.
      "Cache-Control": "public, max-age=3600",
    },
  });
}

function noindex(response: Response): Response {
  const copy = new Response(response.body, response);
  copy.headers.set("X-Robots-Tag", "noindex, nofollow");
  return copy;
}

export default {
  async fetch(request: Request, env: Env, ctx: Ctx): Promise<Response> {
    let response: Response | null = null;
    if (request.method === "GET" || request.method === "HEAD") {
      try {
        response = await questionRedirect(request, env);
      } catch {
        // Fall through to Next.js, which answers this URL on its own.
      }
    }
    response ??= await handler.fetch(request, env, ctx);
    return env.STAGING === "1" ? noindex(response) : response;
  },
};
