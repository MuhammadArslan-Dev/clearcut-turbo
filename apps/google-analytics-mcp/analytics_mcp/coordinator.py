_CLIENT_ID = os.environ.get("GA_MCP_OAUTH_CLIENT_ID")
_CLIENT_SECRET = os.environ.get("GA_MCP_OAUTH_CLIENT_SECRET")
_BASE_URL = os.environ.get("GA_MCP_BASE_URL", "http://localhost:8080")
_JWT_SIGNING_KEY = os.environ.get("GA_MCP_JWT_SIGNING_KEY")

# Google's own scopes. analytics.manage.users is deliberately NOT requested:
# user management stays in the GA4 UI. A Viewer holding the edit scope still
# cannot change anything: GA4 applies the user's role on every call.
REQUIRED_SCOPES = [
    "openid",
    "https://www.googleapis.com/auth/userinfo.email",
    "https://www.googleapis.com/auth/userinfo.profile",
    "https://www.googleapis.com/auth/analytics.readonly",
    "https://www.googleapis.com/auth/analytics.edit",
]

if _CLIENT_ID and _CLIENT_SECRET:
    client_storage = create_client_storage()
    provider_kwargs: dict[str, Any] = {
        "client_id": _CLIENT_ID,
        "client_secret": _CLIENT_SECRET,
        "base_url": _BASE_URL,
        "required_scopes": REQUIRED_SCOPES,
    }
    if _JWT_SIGNING_KEY:
        provider_kwargs["jwt_signing_key"] = _JWT_SIGNING_KEY
    if client_storage is not None:
        provider_kwargs["client_storage"] = client_storage

    mcp = FastMCP("Google Analytics Server", auth=GoogleProvider(**provider_kwargs))

    # Fail closed: with OAuth on, anyone with a Google account could otherwise
    # sign in, so the team allowlist is mandatory.
    _emails, _domains = parse_allowlist(os.environ.get(ALLOWED_EMAILS_ENV))
    if not _emails and not _domains:
        raise RuntimeError(
            f"{ALLOWED_EMAILS_ENV} must list the team's emails or @domains "
            "when OAuth is enabled."
        )
    mcp.add_middleware(TeamOnlyMiddleware(_emails, _domains))
else:
    mcp = FastMCP("Google Analytics Server")


def ensure_subscriptions_listen(server: FastMCP) -> bool:
    """Registers the MCP 2026 subscription stream when FastMCP omits it.

    Same compatibility shim as the Google Ads server: some modern clients open
    ``subscriptions/listen`` while loading tools and break without it.
    Returns True when the handler was installed.
    """
    low_level_server = server._mcp_server
    if "subscriptions/listen" in low_level_server._request_handlers:
        return False

    low_level_server.add_request_handler(
        "subscriptions/listen",
        mcp_types.SubscriptionsListenRequestParams,
        ListenHandler(InMemorySubscriptionBus()),
    )
    return True


ensure_subscriptions_listen(mcp)

_READ_ONLY = ToolAnnotations(
    readOnlyHint=True, destructiveHint=False, openWorldHint=True
)
_WRITE = ToolAnnotations(
    readOnlyHint=False,
    destructiveHint=False,
    idempotentHint=False,
    openWorldHint=True,
)

# (function, description override or None) -- descriptions of the four report
# tools are generated by upstream helpers.
READ_TOOLS = [
    (get_account_summaries, None),
    (list_google_ads_links, None),
    (get_property_details, None),
    (list_property_annotations, None),
    (get_custom_dimensions_and_metrics, None),
    (run_report, _run_report_description()),
    (run_realtime_report, _run_realtime_report_description()),
    (run_funnel_report, _run_funnel_report_description()),
    (run_conversions_report, _run_conversions_report_description()),
]

WRITE_TOOLS = [
    create_property_annotation,
    create_key_event,
    create_custom_dimension,
    create_custom_metric,
    create_audience,
    update_data_retention_settings,
]

for _fn, _description in READ_TOOLS:
    mcp.add_tool(
        Tool.from_function(_fn, description=_description, annotations=_READ_ONLY)
    )
for _fn in WRITE_TOOLS:
    mcp.add_tool(Tool.from_function(_fn, annotations=_WRITE))
